"""Generates go/internal/validator/schema_gen.go from the ORIGINAL ReportValidator.

Usage: python3 -I go/tools/gen_report_schema.py <repo_root> <out_file>

The schema and the patterns are read from a ReportValidator instance, never typed
by hand, so the Go validator always uses the same rules as the Python one.
"""

import json
import sys

repo, out_file = sys.argv[1], sys.argv[2]
sys.path.insert(0, repo)

from Scripts import report_validator  # noqa: E402

v = report_validator.ReportValidator()
KINDS = {dict: "KindDict", str: "KindStr", list: "KindList"}


def q(s):
    return json.dumps(s)


def emit(rule):
    unknown = set(rule) - {"type", "required", "pattern", "schema", "values_rule", "item_rule"}
    assert not unknown, unknown
    parts = ["Type: " + KINDS[rule["type"]]]
    if "required" in rule:
        parts.append("HasRequired: true")
        parts.append("Required: " + ("true" if rule["required"] else "false"))
    if "pattern" in rule:
        parts.append("HasPattern: true")
        parts.append("Pattern: " + q(rule["pattern"]))
    if "schema" in rule:
        fields = ", ".join("{Key: %s, Rule: %s}" % (q(k), emit(r)) for k, r in rule["schema"].items())
        parts.append("Schema: []Field{%s}" % fields)
    if "values_rule" in rule:
        parts.append("ValuesRule: " + emit(rule["values_rule"]))
    if "item_rule" in rule:
        parts.append("ItemRule: " + emit(rule["item_rule"]))
    return "&Rule{" + ", ".join(parts) + "}"


lines = ["// Code generated by go/tools/gen_report_schema.py from Scripts/report_validator.py. DO NOT EDIT.\n\n",
         "package validator\n\n",
         "// NotEmptyPattern is PATTERNS[\"not_empty\"].\nconst NotEmptyPattern = %s\n\n" % q(v.PATTERNS["not_empty"]),
         "// Schema is ReportValidator.SCHEMA.\nvar Schema = %s\n" % emit(v.SCHEMA)]
with open(out_file, "w", encoding="utf-8") as f:
    f.write("".join(lines))
print("generated schema with", len(v.SCHEMA["schema"]), "top-level keys")
