"""Generates the Go dataset files from the ORIGINAL Scripts/datasets modules.

Usage: python3 -I go/tools/gen_datasets.py <repo_root> <out_dir>

Writes into <out_dir> (package datasets):
  kext_data_gen.go, pci_data_gen.go, cpu_data_gen.go, codec_layouts_gen.go, acpi_patch_gen.go
Values are read from the Python objects, never typed by hand. Darwin version
defaults are resolved by the original KextInfo constructor and copied as-is.
"""

import os
import sys

repo, out_dir = sys.argv[1], sys.argv[2]
sys.path.insert(0, repo)

from Scripts.datasets import acpi_patch_data, chipset_data, codec_layouts, cpu_data, kext_data, pci_data  # noqa: E402

# kext_data draws some download IDs at import time (random.choices, 9 digits).
# Reloading it shows which entries change, so the generated code draws them too.
import importlib  # noqa: E402

_first = {k.name: (k.download_info or {}).get("id") for k in kext_data.kexts}
importlib.reload(kext_data)
_second = {k.name: (k.download_info or {}).get("id") for k in kext_data.kexts}
RANDOM_ID_KEXTS = {name for name in _first if _first[name] != _second[name]}

HEADER = "// Code generated by go/tools/gen_datasets.py from Scripts/datasets. DO NOT EDIT.\n\npackage datasets\n\n"


def q(value):
    """Go string literal for a Python str (or empty for None)."""
    if value is None:
        return '""'
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def go_value(value):
    """Go literal for the JSON-like values stored in kext download_info."""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return "int64({})".format(value)
    if value is None:
        return "nil"
    return q(value)


def write(name, body):
    with open(os.path.join(out_dir, name), "w", encoding="utf-8") as f:
        f.write(body)


# ---- kext_data.py ----------------------------------------------------------
lines = [HEADER]
lines.append("// kextCatalog is kext_data.kexts, in the same order.\n")
lines.append("var kextCatalog = []KextInfo{\n")
for kext in kext_data.kexts:
    fields = [
        "Name: {}".format(q(kext.name)),
        "Description: {}".format(q(kext.description)),
        "Category: {}".format(q(kext.category)),
        "Required: {}".format("true" if kext.required else "false"),
        "MinDarwinVersion: {}".format(q(kext.min_darwin_version)),
        "MaxDarwinVersion: {}".format(q(kext.max_darwin_version)),
        "RequiresKexts: []string{{{}}}".format(", ".join(q(r) for r in kext.requires_kexts)),
        "ConflictGroupID: {}".format(q(kext.conflict_group_id)),
        "AllowForceLoad: {}".format("true" if kext.allow_force_load else "false"),
    ]
    if kext.github_repo:
        fields.append("GithubRepo: &Repo{{Owner: {}, Repo: {}}}".format(
            q(kext.github_repo["owner"]), q(kext.github_repo["repo"])))
    if kext.name in RANDOM_ID_KEXTS:
        fields.append("RandomDownloadID: true")
    if kext.download_info:
        pairs = []
        for key, value in kext.download_info.items():
            pairs.append("{}, {}".format(q(key), go_value(value)))
        fields.append("DownloadInfo: dictOf({})".format(", ".join(pairs)))
    lines.append("\t{{{}}},\n".format(", ".join(fields)))
lines.append("}\n\n")
lines.append("// KextIndexByName is kext_data.kext_index_by_name.\n")
lines.append("var KextIndexByName = map[string]int{\n")
for index, kext in enumerate(kext_data.kexts):
    lines.append("\t{}: {},\n".format(q(kext.name), index))
lines.append("}\n")
write("kext_data_gen.go", "".join(lines))

# ---- pci_data.py -----------------------------------------------------------
lines = [HEADER]
for name in sorted(vars(pci_data)):
    value = getattr(pci_data, name)
    if name.startswith("_") or not isinstance(value, (list, tuple)):
        continue
    if name == "UnsupportedUSBControllerIDs":
        continue
    if isinstance(value, dict):
        continue
    if not all(isinstance(x, str) for x in value):
        raise SystemExit("unexpected element type in {}".format(name))
    go_type = "[]string"
    items = ", ".join(q(x) for x in value)
    exported = name[0].upper() + name[1:]
    lines.append("var {} = {}{{{}}}\n\n".format(exported, go_type, items))

lines.append("// UnsupportedUSBControllerIDs is pci_data.UnsupportedUSBControllerIDs. The second\n")
lines.append("// field is a tuple in Python, or a plain string for a few entries.\n")
lines.append("var UnsupportedUSBControllerIDs = []USBControllerEntry{\n")
for device, subsystem in pci_data.UnsupportedUSBControllerIDs:
    if isinstance(subsystem, str):
        value = "SubsystemIDs{{Text: {}, IsString: true}}".format(q(subsystem))
    else:
        value = "SubsystemIDs{{List: []string{{{}}}}}".format(", ".join(q(x) for x in subsystem))
    lines.append("\t{{Device: {}, Subsystem: {}}},\n".format(q(device), value))
lines.append("}\n")
write("pci_data_gen.go", "".join(lines))

# dict-valued entries: each value is a str or a tuple of str, kept in order.
lines = [HEADER]
lines.append("// IDEntry is one key of a pci_data dictionary, in insertion order.\n")
for name in ("ChromebookIDs", "SpoofGPUIDs", "ThinkPadTWX30IDs", "UnsupportedNVMeSSDIDs"):
    value = getattr(pci_data, name)
    items = []
    for key, val in value.items():
        if isinstance(val, str):
            v = "SubsystemIDs{{Text: {}, IsString: true}}".format(q(val))
        else:
            v = "SubsystemIDs{{List: []string{{{}}}}}".format(", ".join(q(x) for x in val))
        items.append("{{Key: {}, Value: {}}}".format(q(key), v))
    exported = name
    lines.append("var {} = []IDEntry{{{}}}\n\n".format(exported, ", ".join(items)))
write("pci_dict_gen.go", "".join(lines))

# ---- chipset_data.py -------------------------------------------------------
lines = [HEADER]
for name in ("IntelChipsets", "AMDChipsets"):
    items = ", ".join(q(x) for x in getattr(chipset_data, name))
    lines.append("var {} = []string{{{}}}\n\n".format(name, items))
write("chipset_data_gen.go", "".join(lines))

# ---- acpi_patch_data.py ----------------------------------------------------
lines = [HEADER]
items = ", ".join(
    "{{Name: {}, Description: {}, FunctionName: {}}}".format(q(p.name), q(p.description), q(p.function_name))
    for p in acpi_patch_data.patches
)
lines.append("// ACPIPatches is acpi_patch_data.patches, in order.\nvar ACPIPatches = []ACPIPatchInfo{{{}}}\n".format(items))
write("acpi_patch_gen.go", "".join(lines))

# ---- cpu_data.py -----------------------------------------------------------
lines = [HEADER]
for name in ("AMDCPUGenerations", "IntelCPUGenerations"):
    items = ", ".join(q(x) for x in getattr(cpu_data, name))
    lines.append("var {} = []string{{{}}}\n\n".format(name, items))
write("cpu_data_gen.go", "".join(lines))

# ---- codec_layouts.py ------------------------------------------------------
lines = [HEADER]
lines.append("// CodecLayouts is codec_layouts.data, keyed by Device ID.\n")
lines.append("var CodecLayouts = map[string][]CodecLayout{\n")
for key, layouts in codec_layouts.data.items():
    items = ", ".join("{{ID: {}, Comment: {}}}".format(layout.id, q(layout.comment)) for layout in layouts)
    lines.append("\t{}: {{{}}},\n".format(q(key), items))
lines.append("}\n")
write("codec_layouts_gen.go", "".join(lines))

print("generated", len(kext_data.kexts), "kexts,", len(codec_layouts.data), "codec keys")
